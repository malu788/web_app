function changeLang(lang) {

  localStorage.setItem("lang", lang);

  const btn = document.getElementById("btn-whatsapp");

  if(btn){
    btn.innerText = translations[lang].whatsapp;

    btn.href =
      "https://wa.me/573103875988?text=" +
      encodeURIComponent(translations[lang].mensajes);
  }

  const missionEl = document.getElementById("mission-text");

  if (missionEl && translations[lang].mission_text) {
    missionEl.innerHTML = translations[lang].mission_text;
  }

  document.querySelectorAll("[data-key], [data-lang]").forEach(el => {

    const key =
      el.getAttribute("data-key") ||
      el.getAttribute("data-lang");

    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }

  });

}

window.onload = () => {

  const savedLang =
    localStorage.getItem("lang") || "it";

  changeLang(savedLang);

};
